export function fillQuestion(
  unit: Unit,
  index: number,
  word: string,
  pron: string,
  meaning?: string,
  id = `${unit.id}-f${index}`,
): Question {
  const chars = [...word],
    exact = chars.findIndex((ch) => unit.jamos.split(' ').includes(jongOf(ch))),
    keyIdx = exact >= 0 ? exact : keyIdxOf(word, unit),
    answer = jongOf(chars[keyIdx])
  const alternatives =
    unit.part === 2
      ? ['ㄳ', 'ㄵ', 'ㄶ', 'ㄼ', 'ㄾ', 'ㅀ', 'ㅄ', 'ㄺ', 'ㄻ', 'ㄿ']
      : ['ㄱ', 'ㄴ', 'ㄷ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅅ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ', 'ㅆ', 'ㄲ']
  const choices = shuffle([answer, ...shuffle(alternatives.filter((j) => j !== answer)).slice(0, 2)])
  return {
    id,
    unitId: unit.id,
    level: 'word',
    format: 'hear',
    target: word,
    pron,
    keyIdx,
    audio: pron,
    prompt: '빠진 받침을 채워요',
    correctSpeak: pron,
    meaning,
    fill: {
      before: chars.slice(0, keyIdx).join(''),
      base: withJong(chars[keyIdx], ''),
      after: chars.slice(keyIdx + 1).join(''),
    },
    options: choices.map((label) => ({
      label,
      kind: label === answer ? 'correct' : 'swap',
      correct: label === answer,
      speak: label,
      feedback: `${word}의 빠진 받침은 ${answer}이에요. [${pron}] 하고 읽어요.`,
    })),
  }
}

