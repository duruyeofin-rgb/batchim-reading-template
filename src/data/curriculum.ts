/** 퀴즈에 실제로 내는 낱말(원래 번호 i 포함). 도전 낱말이 있는 단원은 도전 낱말만 */
export function activeWords(unit: Unit): { w: Word; i: number }[] {
  const hard = unit.words.some((x) => x.tier === 2)
  return unit.words.map((w, i) => ({ w, i })).filter(({ w }) => !hard || w.tier === 2)
}

/** 퀴즈에 실제로 내는 문장 */
export function activeSentences(unit: Unit): { s: Sentence; i: number }[] {
  const hard = unit.sentences.some((x) => x.tier === 2)
  return unit.sentences.map((s, i) => ({ s, i })).filter(({ s }) => !hard || s.tier === 2)
}

