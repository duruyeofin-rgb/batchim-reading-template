export type QType = 'sound' | 'hear'

export interface Word {
  text: string
  pron: string
  type: QType
  wrong?: string // 지정 오답 (sound형)
  special?: boolean // 밟다처럼 예외인 낱말
  tier?: 1 | 2 // 2 = 도전(어려운) 낱말. 생략하면 1
}

export interface Sentence {
  text: string
  target: string // 문장 속 목표 낱말(어절 일부 포함 가능)
  pron: string // 목표 낱말의 발음
  at?: number // 같은 낱말이 여러 번 나올 때 몇 번째인지(0부터)
  tier?: 1 | 2 // 2 = 도전(어려운) 문장. 생략하면 1
}

export interface Unit {
  id: string
  part: 1 | 2
  title: string // 화면에 보일 제목
  short: string // 지도에 보일 짧은 이름
  sound?: string // 1부: 대표음 (ㄱ, ㄴ, ㄷ …)
  jamos: string // 이 단원의 받침 글자들
  rule?: 'front' | 'back' // 2부: 앞/뒤 글자로 읽기
  sentType: QType
  words: Word[]
  sentences: Sentence[]
}

const w = (text: string, pron: string, wrong: string, special = false): Word => ({
  text,
  pron,
  type: 'sound',
  wrong,
  ...(special ? { special } : {}),
})
const h = (text: string): Word => ({ text, pron: text, type: 'hear' })
const s = (text: string, target: string, pron?: string, at?: number): Sentence => ({
  text,
  target,
  pron: pron ?? target,
  ...(at ? { at } : {}),
})

