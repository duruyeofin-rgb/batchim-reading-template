export interface ItemInfo {
  unit: Unit
  level: 'word' | 'sentence'
  text: string // 낱말 또는 목표 낱말
  pron: string
}

/** item_id → 문항 정보 (교사 화면에서 '자주 틀린 받침' 집계에 사용) */
export const ITEM_INDEX: Record<string, ItemInfo> = (() => {
  const m: Record<string, ItemInfo> = {}
  for (const u of UNITS) {
    u.words.forEach((x, i) => (m[wordItemId(u, i)] = { unit: u, level: 'word', text: x.text, pron: x.pron }))
    u.sentences.forEach((x, i) => (m[sentItemId(u, i)] = { unit: u, level: 'sentence', text: x.target, pron: x.pron }))
  }
  return m
})()

export const unitLabel = (unitId: string) => {
  if (unitId.startsWith('story-')) return `이야기 ${unitId.slice(6)}`
  if (unitId.startsWith('read-')) {
    const [, level] = unitId.split('-')
    const b = bookByUnitId(unitId)
    return `읽기 L${level} · ${b ? b.title : unitId}`
  }
  const u = unitById(unitId)
  return u ? `${u.id} ${u.title}` : unitId
}
