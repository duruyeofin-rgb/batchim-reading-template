// ───────── 1부 도전 단계 (홑받침 단원의 수준 올리기) ─────────
// 1부 단원에는 위의 '기초' 낱말·문장(tier 1) 뒤에 '도전' 낱말·문장(tier 2)을 덧붙였다.
// 도전 항목이 있는 단원은 퀴즈에서 도전 항목만 낸다. (기초 항목은 기록·그림의 문항 번호를 지키려고 데이터에 남겨 둔다.)
//  - 도전 낱말: 2~4음절 일상·학교·자연 어휘. 단원의 받침 소리가 들어 있다.
//  - hw('낱말', '발음')  발음이 낱말과 같으면 발음을 생략
//  - hs('문장', '목표 낱말', '발음')
// 도전 낱말을 더 늘리거나 고치려면 이 표에서 하면 된다. (수업이 시작된 뒤에는 기존 항목의 순서를 바꾸지 말고 뒤에만 추가)
const hw = (text: string, pron?: string, special = false): Word => ({
  text,
  pron: pron ?? text,
  type: 'hear',
  tier: 2,
  ...(special ? { special } : {}),
})
const hs = (text: string, target: string, pron?: string): Sentence => ({ text, target, pron: pron ?? target, tier: 2 })

