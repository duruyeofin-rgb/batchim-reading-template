export function realWordChoices(target: string): [string, string] {
  if (LISTENING_CHOICES[target]) return LISTENING_CHOICES[target]
  const score = (word: string) => {
    let n = Math.abs(word.length - target.length) * 5
    for (let i = 0; i < Math.min(word.length, target.length); i++) {
      const a = word.charCodeAt(i) - 0xac00, b = target.charCodeAt(i) - 0xac00
      n += Math.floor(a / 588) === Math.floor(b / 588) ? 0 : 2
      n += Math.floor(a / 28) % 21 === Math.floor(b / 28) % 21 ? 0 : 2
      n += a % 28 === b % 28 ? 0 : 1
    }
    return n
  }
  return WORDS.filter(w => w !== target).sort((a, b) => score(a) - score(b)).slice(0, 2) as [string, string]
}
